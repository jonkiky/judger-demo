const {chromium} = require('../frontend/node_modules/@playwright/test');
const fs = require('node:fs');
const path = require('node:path');
const root=path.resolve(__dirname,'..');
(async()=>{
  const browser=await chromium.launch({channel:'chrome',headless:true});
  const page=await browser.newPage({viewport:{width:1440,height:1080},deviceScaleFactor:1});
  const errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto('http://127.0.0.1:8765');
  const credentials=JSON.parse(fs.readFileSync(path.join(root,'data/local-credentials.json'),'utf8'));
  await page.getByLabel('密码',{exact:true}).fill(credentials.password);
  await page.getByRole('button',{name:'进入工作区'}).click();
  await page.getByRole('heading',{name:'案情有序，研究有据。'}).waitFor();
  fs.mkdirSync(path.join(root,'evaluation/screenshots'),{recursive:true});
  await page.screenshot({path:path.join(root,'evaluation/screenshots/01-home.png'),fullPage:true});
  await page.getByRole('link',{name:/我的案件/}).first().click();
  await page.getByRole('button',{name:'新建案件',exact:true}).click();
  await page.getByLabel('案件名称').fill('珠海购房按揭争议 · 虚构验收案例');
  await page.getByLabel('当前诉求与研究目标').fill('购房人拟解除商品房买卖合同及银行按揭贷款合同，核查退款清算、证据、期间与诉讼路径。');
  await page.getByLabel('研究时点').fill('2026-11-06');
  await page.getByRole('button',{name:'建立并添加材料'}).click();
  await page.waitForURL('**/materials');
  const caseId=page.url().split('/')[4];
  const upload=page.waitForResponse(r=>r.url().endsWith('/materials')&&r.request().method()==='POST');
  await page.getByLabel('上传案件材料').setInputFiles(path.join(root,'evaluation/samples/珠海购房按揭争议_虚构测试案卷.docx'));
  const uploaded=await (await upload).json();
  await page.getByText('已解析',{exact:true}).waitFor();
  await page.screenshot({path:path.join(root,'evaluation/screenshots/02-upload.png'),fullPage:true});
  await page.getByRole('button',{name:'珠海购房按揭争议_虚构测试案卷.docx',exact:true}).click();
  await page.getByRole('region',{name:'来源原文'}).waitFor();
  await page.getByRole('heading',{name:'珠海购房按揭争议_虚构测试案卷.docx',exact:true}).waitFor();
  await page.screenshot({path:path.join(root,'evaluation/screenshots/03-source.png'),fullPage:true});
  await page.getByRole('button',{name:'关闭来源'}).click();
  await page.getByRole('link',{name:'结果与研究',exact:true}).click();
  await page.getByLabel('研究消息').fill('站在购房人代理律师立场，分析本案并制定具体诉讼策略；包括解除银行按揭贷款合同的条件、证据分析、诉讼参与人、主位与备位请求、期间和风险。');
  const runResponse=page.waitForResponse(r=>r.url().endsWith('/requests')&&r.request().method()==='POST');
  await page.getByRole('button',{name:'发送',exact:true}).click();
  const run=await (await runResponse).json();
  await page.reload();
  await page.getByRole('heading',{name:'结果与研究',exact:true}).waitFor();
  await page.screenshot({path:path.join(root,'evaluation/screenshots/04-running.png'),fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:path.join(root,'evaluation/screenshots/05-mobile.png'),fullPage:true});
  const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth);
  const result={case_id:caseId,material:uploaded,run_id:run.id,errors,mobile_horizontal_overflow:overflow,upload_via_browser:true};
  fs.writeFileSync(path.join(root,'evaluation/browser-upload.json'),JSON.stringify(result,null,2));
  console.log(JSON.stringify(result));
  await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
