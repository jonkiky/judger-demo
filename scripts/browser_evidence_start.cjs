const {chromium,expect:baseExpect}=require('../frontend/node_modules/@playwright/test');
const expect=baseExpect.configure({timeout:20000});
const fs=require('node:fs');const path=require('node:path');
const root=path.resolve(__dirname,'..');
(async()=>{
  const {case_id}=JSON.parse(fs.readFileSync(path.join(root,'evaluation/acceptance-runs.json')));
  const credentials=JSON.parse(fs.readFileSync(path.join(root,'data/local-credentials.json')));
  const browser=await chromium.launch({channel:'chrome',headless:true});
  const page=await browser.newPage({viewport:{width:1440,height:1080}});const errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto('http://127.0.0.1:8765');
  await page.getByLabel('密码',{exact:true}).fill(credentials.password);
  await page.getByRole('button',{name:'进入工作区'}).click();
  await page.getByRole('link',{name:'类案检索',exact:true}).waitFor();
  await expect.poll(async()=>{
    const health=await page.request.get('http://127.0.0.1:8765/api/v1/health');
    return health.ok()?(await health.json()).services?.search?.status:'unavailable';
  },{timeout:120000,intervals:[1000,2000,3000]}).toBe('ready');
  await page.goto('http://127.0.0.1:8765/cases/'+case_id+'/evidence');
  const start=page.getByRole('button',{name:/^(重新自动分析|开始自动分析)$/});
  await expect(start).toBeEnabled();
  const accepted=page.waitForResponse(r=>r.url().endsWith('/requests')&&r.request().method()==='POST');
  await start.click();const response=await accepted;
  if(response.status()!==202)throw new Error(await response.text());
  const run=await response.json();
  const record={case_id,run_id:run.id,started_from_browser:true,automatic_selection:true,page_errors:errors};
  fs.writeFileSync(path.join(root,'evaluation/evidence-live-run.json'),JSON.stringify(record,null,2));
  console.log(JSON.stringify(record));
  await expect(page.getByRole('region',{name:'类案证据分析进度',exact:true})).toHaveAttribute('data-run-id',run.id);
  await expect(page.locator('.evidence-agent')).toHaveCount(5,{timeout:180000});
  await expect(page.getByRole('button',{name:'重新自动分析',exact:true})).toBeDisabled();
  await page.screenshot({path:path.join(root,'evaluation/screenshots/evidence-agents-running.png'),fullPage:true});
  const progress=await (await page.request.get('http://127.0.0.1:8765/api/v1/runs/'+run.id+'/evidence')).json();
  if(progress.run_status==='waiting_input')throw new Error('Automatic evidence run asked for selection');
  record.initial_progress=progress;
  fs.writeFileSync(path.join(root,'evaluation/evidence-live-run.json'),JSON.stringify(record,null,2));
  if(errors.length)throw new Error(errors.join('\n'));
  await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
